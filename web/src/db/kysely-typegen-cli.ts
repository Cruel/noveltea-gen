import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { generate, SqliteDialect as SqliteCodegenDialect } from 'kysely-codegen'
import { format, resolveConfig } from 'prettier'
import { migrateStudioKysely, openStudioSchemaConnection } from './kysely-migrations'
import { studioDdl } from './kysely-baseline'

/**
 * Recreate, migrate and introspect a fresh temporary SQLite database every run.
 * There is deliberately no path to a developer or Compose database here.
 */
export async function generatedStudioDb(): Promise<string> {
  const directory = mkdtempSync(join(tmpdir(), 'noveltea-typegen-'))
  const connection = openStudioSchemaConnection({ backend: 'sqlite', path: join(directory, 'fresh.sqlite') })
  try {
    await migrateStudioKysely(connection, {
      baseURL: 'http://localhost:3000',
      secret: 'kysely-typegen-isolated-test-only-0123456789',
      github: { clientId: 'typegen', clientSecret: 'typegen' },
      gitlab: { clientId: 'typegen', clientSecret: 'typegen' },
    })
    const baseline = new Set(studioDdl().tables.keys())
    const excluded = new Set([
      'user',
      'account',
      'session',
      'verification',
      'rateLimit',
      'kysely_migration',
      'kysely_migration_lock',
      'studio_migration_sources',
    ])
    const generated = await generate({
      db: connection.db,
      dialect: new SqliteCodegenDialect(),
      camelCase: true,
      skipAutogeneratedFileComment: true,
      outFile: null,
      typeOnlyImports: true,
      postprocess: async ({ metadata }) => {
        metadata.tables = metadata.tables.filter((table) => !excluded.has(table.name))
        const available = new Set(metadata.tables.map((table) => table.name))
        for (const table of baseline)
          if (!available.has(table))
            throw new Error('Missing Studio application table during typegen: ' + table)
        return metadata
      },
    })
    const output = generated.replace(/export interface DB \{/, 'export interface StudioDb {')
    if (output === generated) throw new Error('kysely-codegen DB interface not found')
    const target = fileURLToPath(new URL('./studio-db.ts', import.meta.url))
    const source =
      '// Generated by kysely-codegen 0.20.0 from a freshly migrated SQLite Studio database.\n' +
      '// Do not edit. Run pnpm --filter @noveltea/studio typegen to regenerate.\n' +
      '// Physical TEXT JSON and timestamps are strings; INTEGER booleans are 0/1.\n' +
      output
    // Formatting is part of generation; running pnpm format must not
    // invalidate the committed typegen:check output.
    return format(source, { ...(await resolveConfig(target)), filepath: target })
  } finally {
    await connection.close()
    rmSync(directory, { recursive: true, force: true })
  }
}

const args = process.argv.slice(2)
if (args.length > 1 || (args.length === 1 && args[0] !== '--check'))
  throw new Error('Usage: typegen [--check]')
const target = fileURLToPath(new URL('./studio-db.ts', import.meta.url))
const result = await generatedStudioDb()
if (args[0] === '--check') {
  if (!existsSync(target) || readFileSync(target, 'utf8') !== result)
    throw new Error('Committed StudioDb differs from fresh kysely-codegen output. Run pnpm typegen.')
  console.log('Canonical StudioDb matches fresh SQLite kysely-codegen output.')
} else {
  writeFileSync(target, result)
  console.log('Regenerated canonical StudioDb from fresh SQLite Kysely migrations.')
}
